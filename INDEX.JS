/* =========================================
   VARIABEL
========================================= */

let currentPage = 0;

const totalPages = storyPages.length;


/* =========================================
   ELEMENT
========================================= */

const coverPage =
    document.getElementById("coverPage");

const storyPage =
    document.getElementById("storyPage");

const storyTitle =
    document.getElementById("storyTitle");

const chapterNumber =
    document.getElementById("chapterNumber");

const storyContent =
    document.getElementById("storyContent");

const storyQuote =
    document.getElementById("storyQuote");


const currentPageElement =
    document.getElementById("currentPage");

const pageIndicator =
    document.getElementById("pageIndicator");

const prevBtn =
    document.getElementById("prevBtn");

const nextBtn =
    document.getElementById("nextBtn");


/* =========================================
   TAMPILKAN HALAMAN
========================================= */

function showPage() {

    /* COVER */
    if (currentPage === 0) {

        coverPage.classList.add("active");

        storyPage.classList.remove("active");

        currentPageElement.textContent = "1";

        pageIndicator.textContent =
            "Halaman 1 / 15";

        prevBtn.disabled = true;

        nextBtn.disabled = false;

        return;
    }


    /* CERITA */

    coverPage.classList.remove("active");

    storyPage.classList.add("active");


    const story =
        storyPages[currentPage - 1];


    chapterNumber.textContent =
        "BAB " + currentPage;


    storyTitle.textContent =
        story.title;


    storyContent.innerHTML =
        story.text;


    storyQuote.textContent =
        story.quote;
        
        
    /* NOMOR HALAMAN */

    currentPageElement.textContent =
        currentPage + 1;


    pageIndicator.textContent =
        "Halaman " +
        (currentPage + 1) +
        " / 15";


    /* BUTTON */

    prevBtn.disabled =
        currentPage === 0;


    nextBtn.disabled =
        currentPage >= totalPages;


    /* KEMBALI KE ATAS */

    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });
}


/* =========================================
   NEXT
========================================= */

nextBtn.addEventListener("click", function () {

    if (currentPage < totalPages) {

        currentPage++;

        showPage();
    }

});


/* =========================================
   PREVIOUS
========================================= */

prevBtn.addEventListener("click", function () {

    if (currentPage > 0) {

        currentPage--;

        showPage();
    }

});


/* =========================================
   DARK MODE
========================================= */

const darkModeBtn =
    document.getElementById("darkModeBtn");


darkModeBtn.addEventListener(
    "click",
    function () {

        document.body.classList.toggle(
            "dark-mode"
        );


        if (
            document.body.classList.contains(
                "dark-mode"
            )
        ) {

            darkModeBtn.textContent = "☀️";

            localStorage.setItem(
                "storyTheme",
                "dark"
            );

        } else {

            darkModeBtn.textContent = "🌙";

            localStorage.setItem(
                "storyTheme",
                "light"
            );
        }

    }
);


/* =========================================
   LOAD THEME
========================================= */

if (
    localStorage.getItem("storyTheme")
    === "dark"
) {

    document.body.classList.add(
        "dark-mode"
    );

    darkModeBtn.textContent = "☀️";
}


/* =========================================
   UKURAN FONT
========================================= */

const fontMinus =
    document.getElementById("fontMinus");

const fontReset =
    document.getElementById("fontReset");

const fontPlus =
    document.getElementById("fontPlus");


let fontSize =
    parseFloat(
        localStorage.getItem("storyFontSize")
    ) || 18;


function updateFontSize() {

    storyContent.style.fontSize =
        fontSize + "px";

    localStorage.setItem(
        "storyFontSize",
        fontSize
    );
}


fontPlus.addEventListener(
    "click",
    function () {

        if (fontSize < 26) {

            fontSize += 1;

            updateFontSize();
        }

    }
);


fontMinus.addEventListener(
    "click",
    function () {

        if (fontSize > 14) {

            fontSize -= 1;

            updateFontSize();
        }

    }
);


fontReset.addEventListener(
    "click",
    function () {

        fontSize = 18;

        updateFontSize();
    }
);


/* =========================================
   KEYBOARD NAVIGATION
========================================= */

document.addEventListener(
    "keydown",
    function (event) {

        if (event.key === "ArrowRight") {

            if (currentPage < totalPages) {

                currentPage++;

                showPage();
            }
        }


        if (event.key === "ArrowLeft") {

            if (currentPage > 0) {

                currentPage--;

                showPage();
            }
        }

    }
);


/* =========================================
   START
========================================= */

updateFontSize();

showPage();
